ALTER TABLE insumos ADD CONSTRAINT ck_insumos_nombre_trim CHECK (nombre = BTRIM(nombre));
CREATE TABLE movimientos_stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    insumo_id BIGINT NOT NULL REFERENCES insumos(id),
    tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('INGRESO', 'EGRESO')),
    cantidad NUMERIC(12,4) NOT NULL CHECK (cantidad > 0),
    motivo VARCHAR(250) NOT NULL,
    stock_resultante NUMERIC(12,4) NOT NULL CHECK (stock_resultante >= 0),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_movimientos_stock_fecha ON movimientos_stock(creado_en DESC);
