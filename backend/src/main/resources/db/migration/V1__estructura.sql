CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(40) NOT NULL UNIQUE,
    password VARCHAR(100) NOT NULL,
    rol VARCHAR(15) NOT NULL CHECK (rol IN ('ADMIN', 'USUARIO'))
);
CREATE TABLE pacientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni VARCHAR(8) NOT NULL UNIQUE CHECK (dni ~ '^[0-9]{8}$'),
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    telefono VARCHAR(9) NOT NULL,
    direccion VARCHAR(250) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE formulas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    presentacion VARCHAR(100) NOT NULL,
    indicaciones VARCHAR(2000) NOT NULL,
    paciente_id BIGINT NOT NULL REFERENCES pacientes(id),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE ingredientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    cantidad NUMERIC(12,4) NOT NULL CHECK (cantidad > 0),
    unidad VARCHAR(10) NOT NULL CHECK (unidad IN ('g', 'ml', 'unidad')),
    formula_id BIGINT NOT NULL REFERENCES formulas(id)
);
CREATE INDEX idx_formulas_paciente ON formulas(paciente_id);
CREATE INDEX idx_ingredientes_formula ON ingredientes(formula_id);
