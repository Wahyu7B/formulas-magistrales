CREATE TABLE insumos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    stock NUMERIC(12,4) NOT NULL DEFAULT 0 CHECK (stock >= 0),
    stock_minimo NUMERIC(12,4) NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
    unidad VARCHAR(10) NOT NULL CHECK (unidad IN ('g', 'ml', 'unidad')),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX uk_insumos_nombre_activo ON insumos (LOWER(nombre)) WHERE activo = TRUE;
